# --- 7.1 Congo Predictions and Mapping
cat("    Processing Congo spatial predictions using inverted Bayesian Sigmoid...\n")
r_congo_cropped <- crop(r_congo, study_extent_congo)
congo_cells <- as.data.frame(r_congo_cropped[["uoi"]], cells = TRUE, xy = TRUE, na.rm = TRUE)
names(congo_cells)[names(congo_cells) == "uoi"] <- "uoi"

# Clamp observed GEDI UOI slightly within fitted limits (uoimin_val, uoimax_val) to avoid domain errors
eps <- 1e-4
congo_cells$uoi_clamped <- pmax(uoimin_val + eps, pmin(uoimax_val - eps, congo_cells$uoi))
congo_cells$pred <- 1000 * (x0_val - (1 / k_val) * log((uoimax_val - congo_cells$uoi_clamped) / (congo_cells$uoi_clamped - uoimin_val)))
congo_cells$pred <- pmax(0, congo_cells$pred)

