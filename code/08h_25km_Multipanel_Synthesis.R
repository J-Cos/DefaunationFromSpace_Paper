# Load robust cluster buffered MCPs
geojson_path <- "outputs/camera_traps_robust_buffered_mcps.geojson"
if (!file.exists(geojson_path)) {
  stop("Camera trap buffered MCPs GeoJSON missing: ", geojson_path, 
       "\nPlease run python3 code/visualise_camera_traps.py first to generate it.")
}
mcps <- terra::vect(geojson_path)
mcps_congo <- mcps[as.vector(values(mcps)$region) == "Congo", ]
mcps_amazon <- mcps[as.vector(values(mcps)$region) == "Amazon", ]
cat(sprintf("✓ Loaded %d Congo and %d Amazon study polygons.\n", nrow(mcps_congo), nrow(mcps_amazon)))

# Establish consistent cropped geographic study extents with 1.0 degree padding
study_extent_congo <- ext(mcps_congo)
study_extent_congo <- ext(
  xmin(study_extent_congo) - 1.0,
  xmax(study_extent_congo) + 1.0,
  ymin(study_extent_congo) - 1.0,
  ymax(study_extent_congo) + 1.0
)

study_extent_amazon <- ext(mcps_amazon)
study_extent_amazon <- ext(
  xmin(study_extent_amazon) - 1.0,
  xmax(study_extent_amazon) + 1.0,
  ymin(study_extent_amazon) - 1.0,
  ymax(study_extent_amazon) + 1.0
)

base_family <- if (requireNamespace("showtext", quietly = TRUE)) "Roboto Condensed" else "sans"

# --- 2. Load 25 km Spatial Stacks --------------------------------------------
r_congo_path <- "outputs/EOdata/analysis_stack_25000_Congo.tif"
r_amazon_path <- "outputs/EOdata/analysis_stack_25000_Amazon.tif"

if (!file.exists(r_congo_path) || !file.exists(r_amazon_path)) {
  stop("25km GEE geotiffs missing. Please run GEE aggregation first.")
}

r_congo <- rast(r_congo_path)
r_amazon <- rast(r_amazon_path)

aggregate_names <- c("frip", "frip_mk_tau", "uoi", "uoi_sd", "rh98", "gedi_n",
                     "elevation", "slope", "hnd", "precip", "clay", "forest_fraction")
names(r_congo) <- aggregate_names
names(r_amazon) <- aggregate_names

# --- 3. Extract Pixel Values and Merge Metadata -----------------------------
cat("  Extracting pixel values inside MCP polygons...\n")
extracted_congo <- terra::extract(r_congo, mcps_congo, df = TRUE, touches = TRUE)
mcp_congo_df <- as.data.frame(mcps_congo)
mcp_congo_df$ID <- 1:nrow(mcp_congo_df)
pixel_congo <- merge(extracted_congo, mcp_congo_df, by = "ID") %>%
  filter(!is.na(uoi)) %>%
  select(-ID) %>%
  mutate(basin = "Congo")

extracted_amazon <- terra::extract(r_amazon, mcps_amazon, df = TRUE, touches = TRUE)
mcp_amazon_df <- as.data.frame(mcps_amazon)
mcp_amazon_df$ID <- 1:nrow(mcp_amazon_df)
pixel_amazon <- merge(extracted_amazon, mcp_amazon_df, by = "ID") %>%
  filter(!is.na(uoi)) %>%
  select(-ID) %>%
  mutate(basin = "Amazon")

pixel_data <- rbind(pixel_congo, pixel_amazon)

# Aggregate to Polygon Means for modeling
joined_data <- pixel_data %>%
  group_by(cluster_id, region, basin, trap_days, n_species, B_H_index, M_H_index, B_H_gt50, B_H_gt100, megafauna_fraction) %>%
  summarise(
    n_pixels = n(),
    uoi_sd = ifelse(is.na(sd(uoi, na.rm = TRUE)), 0, sd(uoi, na.rm = TRUE)),
    uoi = mean(uoi, na.rm = TRUE),
    .groups = "drop"
  ) %>%
  filter(trap_days >= 10)

# Compute standard error of the mean
joined_data <- joined_data %>%
  mutate(uoi_se = uoi_sd / sqrt(n_pixels))

# Regularizing constant
reg_uoi <- median(joined_data$uoi_se[joined_data$uoi_se > 0], na.rm = TRUE)
if (is.na(reg_uoi) || reg_uoi == 0) reg_uoi <- 1e-4

# Dual-weight precision framework
joined_data <- joined_data %>%
  mutate(w_uoi = log10(trap_days) / (uoi_se + reg_uoi))

# Weight normalization (mean = 1)
joined_data$w_uoi_norm <- joined_data$w_uoi / mean(joined_data$w_uoi)

# --- 4. Fit Weight-Normalized Bayesian Sigmoid Model (25 km) ------------------
cat("  Formulating and fitting Bayesian non-linear Sigmoid model (UOI predicted by Biomass)...\n")

# Scale biomass to range [0, 4.5] for better optimization stability
joined_data$B_scaled <- joined_data$B_H_index / 1000

# Formula for non-linear sigmoid:
# UOI = uoimin + (uoimax - uoimin) / (1 + exp(-k * (B_scaled - x0)))
b_formula <- bf(
  uoi | weights(w_uoi_norm) ~ uoimin + (uoimax - uoimin) / (1 + exp(-k * (B_scaled - x0))),
  uoimin + uoimax + k + x0 ~ 1,
  nl = TRUE
)

# Priors with physical bounds to constrain parameters to ecologically realistic ranges:
#   - uoimin: baseline openness around 0.915
#   - uoimax: maximum plateau around 0.965
#   - k: positive steepness prior, scaled to B_scaled (which spans ~4 units)
#   - x0: midpoint of steep change in scaled biomass (e.g., around 1.1, i.e., 1100 kg/ha)
b_priors <- c(
  prior(normal(0.915, 0.02), nlpar = "uoimin", lb = 0.85, ub = 0.95),
  prior(normal(0.965, 0.02), nlpar = "uoimax", lb = 0.94, ub = 0.99),
  prior(normal(2.5, 1.5), nlpar = "k", lb = 0.1, ub = 10.0),
  prior(normal(1.2, 0.5), nlpar = "x0", lb = 0.1, ub = 4.0)
)

# Fit the non-linear model using brms/Stan
fit_bayesian <- brm(
  formula = b_formula,
  data = joined_data,
  family = gaussian(),
  prior = b_priors,
  chains = 4,
  cores = 4,
  iter = 4000,
  warmup = 2000,
  control = list(adapt_delta = 0.98),
  backend = "rstan",
  seed = 42
)

cat("\nBayesian model fit summary:\n")
print(summary(fit_bayesian))
cat("\n")

# Extract posterior parameter estimates for mapping
fe <- fixef(fit_bayesian)
uoimin_val <- fe["uoimin_Intercept", "Estimate"]
uoimax_val <- fe["uoimax_Intercept", "Estimate"]
k_val      <- fe["k_Intercept", "Estimate"]
x0_val     <- fe["x0_Intercept", "Estimate"]

cat(sprintf("✓ Bayesian parameters extracted:\n"))
cat(sprintf("  uoimin = %.4f, uoimax = %.4f, k = %.4f, x0 = %.4f\n", 
            uoimin_val, uoimax_val, k_val, x0_val))

# --- 5. PANEL A: Scatter Plot and Model Fit ----------------------------------
cat("  Generating Panel A (Scatterplot with Bayesian Sigmoid fit)...\n")

# Create sequence of Biomass values for plotting the fit
# Spans 0 to 7500 (representing scaled 0 to 7.5) to capture full range and extrapolation
biomass_seq <- seq(0, 7500, length.out = 300)
pred_df <- data.frame(
  B_H_index = biomass_seq,
  B_scaled = biomass_seq / 1000
)

# Predict expected value of UOI and its 95% Credible Interval
fitted_draws <- fitted(fit_bayesian, newdata = pred_df)
pred_df$fit <- fitted_draws[, "Estimate"]
pred_df$lower <- fitted_draws[, "Q2.5"]
pred_df$upper <- fitted_draws[, "Q97.5"]

stat_label <- sprintf(
  "Bayesian Sigmoid (25 km)\nN = %d clusters\nConverged (Rhat = 1.00)",
  nrow(joined_data)
)

p_scatter <- ggplot() +
  # 95% Credible Interval ribbon (forest green)
  geom_ribbon(
    data = pred_df,
    aes(x = B_H_index, ymin = lower, ymax = upper),
    fill = "#2E7D32",
    alpha = 0.15
  ) +
  # Regression curve
  geom_line(
    data = pred_df,
    aes(x = B_H_index, y = fit),
    color = "#1B5E20",
    linewidth = 0.8
  ) +
  # Empirical points (colored by UOI Spatial SE, shaped by continent)
  geom_point(
    data = joined_data,
    aes(x = B_H_index, y = uoi, size = trap_days,
        fill = uoi_se, shape = basin),
    color = "black",
    stroke = 0.4,
    alpha = 0.85
  ) +
  scale_shape_manual(
    values = c("Congo" = 21, "Amazon" = 24),
    name = "Continent"
  ) +
  scale_size_continuous(
    range = c(1.5, 6.0),
    name = "Effort (Days)"
  ) +
  scale_fill_viridis_c(
    option = "magma",
    name = "UOI Spatial SE",
    guide = guide_colorbar(
      title.position = "top",
      barwidth = unit(1.8, "cm"),
      barheight = unit(0.12, "cm")
    )
  ) +
  annotate(
    "text",
    x = 100, y = 0.969,
    label = stat_label,
    hjust = 0, vjust = 1,
    family = base_family,
    size = 2.4,
    fontface = "bold",
    color = "grey20"
  ) +
  scale_x_continuous(limits = c(0, 7500), expand = c(0, 0)) +
  scale_y_continuous(limits = c(0.91, 0.98), expand = expansion(mult = c(0, 0.01))) +
  theme_pnas(base_size = 7.5) +
  theme(
    legend.position = "bottom",
    legend.box = "horizontal",
    legend.title = element_text(size = 6.0, face = "bold"),
    legend.text = element_text(size = 5.5),
    legend.key.size = unit(0.28, "cm"),
    legend.margin = margin(t = -5, r = 0, b = 0, l = 0, unit = "pt")
  ) +
  labs(
    title = "A. Bayesian Sigmoid Model Fit & Extrapolation",
    x = "Total Mammal Biomass Index",
    y = "GEDI Understory Openness Index (UOI)"
  )

